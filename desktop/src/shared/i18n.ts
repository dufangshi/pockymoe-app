export type MessageKey = keyof typeof english;
export type UiLocale = 'zh-CN' | 'en';
let locale: UiLocale = 'en';
export function resolveLocale(value?: string | null): UiLocale { return /^zh(?:-|$)/i.test(value || '') ? 'zh-CN' : 'en'; }
export function setLocale(value?: string | null): UiLocale { locale = resolveLocale(value); return locale; }
export function getLocale(): UiLocale { return locale; }
export function t(key: MessageKey, values: Record<string, string | number> = {}, language: string = locale): string {
  const template: string = resolveLocale(language) === 'zh-CN' ? key : english[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => Object.hasOwn(values, name) ? String(values[name]) : match);
}

/** Re-localize app-owned static errors/statuses already returned by an action. */
export function localizeMessage(message: string, language: string = locale): string {
  if (Object.hasOwn(english, message)) return t(message as MessageKey, {}, language);
  const key = (Object.keys(english) as MessageKey[]).find(key => english[key] === message);
  return key ? t(key, {}, language) : message;
}
export function formatList(items: string[]): string { return new Intl.ListFormat(locale, { style: 'short', type: 'conjunction' }).format(items); }
